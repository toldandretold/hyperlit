#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# cloudflare-ips.sh — keep "who is Cloudflare" current in the two places the
# droplet needs it: the nginx real-IP snippet and the ufw origin lock.
#
# hyperlit.io is proxied by Cloudflare. Two things follow:
#   1. nginx must take the visitor's IP from CF-Connecting-IP, but ONLY when the
#      connection really comes from Cloudflare (deploy/security/nginx/cloudflare-realip.conf).
#   2. Ports 80/443 should accept connections ONLY from Cloudflare. Otherwise
#      anyone who learns the droplet's address talks to the origin directly and
#      every Cloudflare control (WAF, bot fight, rate limits, Under Attack) is moot.
#
# Cloudflare publishes its ranges at https://www.cloudflare.com/ips-v4 and /ips-v6
# and changes them rarely. This script fetches them and rewrites both artefacts
# idempotently, so it is safe to cron:
#
#   sudo ./deploy/security/cloudflare-ips.sh --nginx --ufw     # first install / by hand
#   sudo ./deploy/security/cloudflare-ips.sh --check           # diff only, change nothing
#
#   # /etc/cron.d/cloudflare-ips  (monthly, quiet; mail/ntfy on change if you like)
#   17 4 1 * * root /var/www/hyperlit/deploy/security/cloudflare-ips.sh --nginx --ufw >> /var/log/cloudflare-ips.log 2>&1
#
# SAFETY: the script refuses to apply a list that looks wrong (fewer than 10 v4
# ranges, or a line that is not a CIDR) — a Cloudflare outage or a captive
# portal must never leave the firewall with an empty allow list (= site down)
# or the real-IP snippet trusting garbage (= spoofable IPs).
#
# ufw rules written by this script carry the comment "cloudflare-origin" and are
# the ONLY rules it ever deletes. Your own rules (SSH etc.) are never touched.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

DO_NGINX=0 DO_UFW=0 CHECK=0
for arg in "$@"; do
    case "${arg}" in
        --nginx) DO_NGINX=1 ;;
        --ufw)   DO_UFW=1 ;;
        --check) CHECK=1 ;;
        -h|--help) sed -n '2,32p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown flag: ${arg} (try --help)" >&2; exit 1 ;;
    esac
done
if [ "${DO_NGINX}${DO_UFW}${CHECK}" = "000" ]; then
    echo "nothing to do: pass --nginx and/or --ufw (or --check)" >&2; exit 1
fi

NGINX_SNIPPET="${NGINX_SNIPPET:-/etc/nginx/snippets/cloudflare-realip.conf}"
CF_V4_URL="https://www.cloudflare.com/ips-v4"
CF_V6_URL="https://www.cloudflare.com/ips-v6"
UFW_COMMENT="cloudflare-origin"

fetch() { curl -fsS --max-time 20 --retry 2 "$1"; }

V4="$(fetch "${CF_V4_URL}" | tr -d '\r' | sed '/^\s*$/d')"
V6="$(fetch "${CF_V6_URL}" | tr -d '\r' | sed '/^\s*$/d')"

# ── sanity: this list becomes the firewall allow list, so be paranoid ─────────
CIDR4_RE='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
CIDR6_RE='^[0-9a-fA-F:]+/[0-9]{1,3}$'
n4=0; n6=0
while IFS= read -r line; do
    [[ "${line}" =~ ${CIDR4_RE} ]] || { echo "refusing: bad IPv4 line from Cloudflare: '${line}'" >&2; exit 2; }
    n4=$((n4 + 1))
done <<< "${V4}"
while IFS= read -r line; do
    [[ "${line}" =~ ${CIDR6_RE} ]] || { echo "refusing: bad IPv6 line from Cloudflare: '${line}'" >&2; exit 2; }
    n6=$((n6 + 1))
done <<< "${V6}"
if [ "${n4}" -lt 10 ] || [ "${n6}" -lt 3 ]; then
    echo "refusing: suspiciously short list (${n4} v4 / ${n6} v6 ranges) — not touching anything" >&2; exit 2
fi
echo "cloudflare publishes ${n4} IPv4 + ${n6} IPv6 ranges"

# ── nginx real-IP snippet ────────────────────────────────────────────────────
render_nginx() {
    cat <<HDR
# GENERATED by deploy/security/cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%MZ) — do not hand-edit.
# Trust ONLY Cloudflare for the visitor IP. Seed/explanation: deploy/security/nginx/cloudflare-realip.conf

HDR
    echo "# Cloudflare IPv4 — ${CF_V4_URL}"
    while IFS= read -r r; do echo "set_real_ip_from ${r};"; done <<< "${V4}"
    echo
    echo "# Cloudflare IPv6 — ${CF_V6_URL}"
    while IFS= read -r r; do echo "set_real_ip_from ${r};"; done <<< "${V6}"
    echo
    echo "real_ip_header CF-Connecting-IP;"
}

if [ "${DO_NGINX}" = 1 ] || [ "${CHECK}" = 1 ]; then
    NEW="$(render_nginx)"
    if [ -f "${NGINX_SNIPPET}" ] && diff -q <(grep -E '^(set_real_ip_from|real_ip_header)' "${NGINX_SNIPPET}") <(echo "${NEW}" | grep -E '^(set_real_ip_from|real_ip_header)') >/dev/null; then
        echo "nginx: ${NGINX_SNIPPET} already current"
    elif [ "${CHECK}" = 1 ]; then
        echo "nginx: ${NGINX_SNIPPET} DIFFERS from Cloudflare's current list (run with --nginx to update)"
    else
        command -v nginx >/dev/null 2>&1 || { echo "nginx not found — skipping snippet" >&2; exit 3; }
        install -d "$(dirname "${NGINX_SNIPPET}")"
        tmp="$(mktemp)"; echo "${NEW}" > "${tmp}"
        # Validate the whole nginx config WITH the new snippet before it goes live.
        backup=""
        if [ -f "${NGINX_SNIPPET}" ]; then backup="${NGINX_SNIPPET}.bak"; cp "${NGINX_SNIPPET}" "${backup}"; fi
        install -m 0644 "${tmp}" "${NGINX_SNIPPET}"; rm -f "${tmp}"
        if nginx -t >/dev/null 2>&1; then
            systemctl reload nginx
            echo "nginx: wrote ${NGINX_SNIPPET} and reloaded"
        else
            echo "nginx -t FAILED with the new snippet — restoring previous" >&2
            if [ -n "${backup}" ]; then mv "${backup}" "${NGINX_SNIPPET}"; else rm -f "${NGINX_SNIPPET}"; fi
            nginx -t; exit 4
        fi
        rm -f "${backup}"
    fi
fi

# ── ufw origin lock ──────────────────────────────────────────────────────────
if [ "${DO_UFW}" = 1 ] || [ "${CHECK}" = 1 ]; then
    command -v ufw >/dev/null 2>&1 || { echo "ufw not installed (apt install ufw) — skipping" >&2; exit 3; }
    WANT="$(printf '%s\n%s\n' "${V4}" "${V6}" | sort)"
    HAVE="$(ufw status 2>/dev/null | grep -F "# ${UFW_COMMENT}" | awk '{print $3}' | sort -u || true)"
    if [ "${WANT}" = "${HAVE}" ]; then
        echo "ufw: ${n4}+${n6} ${UFW_COMMENT} rules already current"
    elif [ "${CHECK}" = 1 ]; then
        echo "ufw: ${UFW_COMMENT} rules DIFFER from Cloudflare's current list (run with --ufw to update)"
    else
        # Add the new set FIRST, then remove stale ones, so there is never a moment
        # with no Cloudflare range allowed (ufw applies each rule immediately).
        for r in ${V4} ${V6}; do
            ufw allow proto tcp from "${r}" to any port 80,443 comment "${UFW_COMMENT}" >/dev/null
        done
        # Delete any cloudflare-origin rule whose source is no longer published.
        # Walk numbered rules from the bottom so numbers stay valid as we delete.
        ufw status numbered | grep -F "# ${UFW_COMMENT}" | tac | while IFS= read -r line; do
            num="$(echo "${line}" | sed -E 's/^\[ *([0-9]+)\].*/\1/')"
            src="$(echo "${line}" | awk -F'ALLOW IN' '{print $2}' | awk '{print $1}')"
            if ! grep -qxF "${src}" <<< "${WANT}"; then
                ufw --force delete "${num}" >/dev/null && echo "ufw: removed stale ${src}"
            fi
        done
        echo "ufw: ${UFW_COMMENT} rules now match Cloudflare (${n4} v4 + ${n6} v6)"
        echo "ufw: NOTE this only manages the 80/443 Cloudflare allow rules. Default-deny incoming,"
        echo "     your SSH rule and 'ufw enable' are one-off steps in deploy/security/README.md."
    fi
fi
