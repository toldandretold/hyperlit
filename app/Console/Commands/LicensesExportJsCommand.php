<?php

namespace App\Console\Commands;

use App\Support\Licenses;
use Illuminate\Console\Command;

/**
 * Writes the licence vocabulary (App\Support\Licenses) to the front end as a generated TS
 * module, so the reader's label map and the picker can never disagree with what the server
 * accepts. tests/Unit/Licensing/LicensesExportParityTest.php fails when the committed file is
 * stale — re-run this and commit the result.
 */
class LicensesExportJsCommand extends Command
{
    protected $signature = 'licenses:export-js {--check : exit non-zero if the committed file is stale}';

    protected $description = 'Generate resources/js/components/sourceContainer/licenses.generated.ts from App\\Support\\Licenses';

    public const PATH = 'resources/js/components/sourceContainer/licenses.generated.ts';

    public function handle(): int
    {
        $path = base_path(self::PATH);
        $content = self::render();

        if ($this->option('check')) {
            $ok = is_file($path) && file_get_contents($path) === $content;
            $this->line($ok ? 'licenses.generated.ts is up to date.' : 'licenses.generated.ts is STALE — run php artisan licenses:export-js');

            return $ok ? self::SUCCESS : self::FAILURE;
        }

        file_put_contents($path, $content);
        $this->info('Wrote ' . self::PATH);

        return self::SUCCESS;
    }

    public static function render(): string
    {
        $json = json_encode(Licenses::all(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        $default = Licenses::DEFAULT_USER;
        $unknown = Licenses::UNKNOWN;
        $custom = Licenses::CUSTOM;

        return <<<TS
// GENERATED by `php artisan licenses:export-js` from app/Support/Licenses.php — DO NOT EDIT.
// The server is the source of truth for licence codes; a parity test fails if this drifts.

export interface LicenseDef {
  label: string;
  url: string | null;
  selectable: boolean;
  group: 'hyperlit' | 'cc' | 'public-domain' | 'other' | 'custom';
}

export const DEFAULT_USER_LICENSE = '{$default}';
export const UNKNOWN_LICENSE = '{$unknown}';
export const CUSTOM_LICENSE = '{$custom}';

export const LICENSES: Record<string, LicenseDef> = {$json};

TS;
    }
}
